using VascularTrees
using VascularTrees.TreesProcessing:
    process_julia_graph,
    process_terminal_nodes

# Definitions of the available tree configurations (inflow / outflow trees)
const trees::TreeDefinitions = TreeDefinitions()

"""
    main(; t_options, debug, find_closest_tnodes, m_options)

Convert graphs generated by SyntheticVascularTrees.jl into .arrow tables used by the simulations.

Run: `julia --project scripts/build_arrow_graphs.jl`, or in the REPL
`include("scripts/build_arrow_graphs.jl")` (or `includet` with Revise loaded), then
`main(t_options = TreeOptions(n_nodes = [10], tree_configurations = ["Rectangle_quad"]), find_closest_tnodes = true)`.

What must be specified (keyword arguments, defaults below):
1. t_options (tree configurations and numbers of nodes)
2. find_closest_tnodes (boolean flag to determine if closest terminal nodes should be found)
3. m_options (how the closest terminal nodes are matched, see `MatchingOptions`)

Supported configurations: those in `TreeDefinitions` (src/common/definitions.jl),
currently "Rectangle_quad" and "Rectangle_trio".

Inputs (per vascular tree, e.g. A, P, V, B), expected in
`results/julia_vessel_trees/<tree_configuration>/<tree_configuration>_<n_nodes>/julia/`:
1. `<tree>.lg`        - edge list (graph skeleton)
2. `<tree>_edges.csv` - edge attributes
3. `<tree>_nodes.csv` - node attributes

Outputs, in the `graphs/` folder of the graph directory:
1. `<tree>.arrow` - one table per vascular tree (ODE groups, ids, flows, volumes, ...)
2. `T.arrow`      - terminal nodes, i.e. the connection points between the trees
"""
function main(;
    # === Graph options ===
    # options for graph, i.e., number of nodes and type of tree
    t_options = TreeOptions(
        n_nodes = [10, 100, 1000, 10000, 100000, 1000000, 10000000],  #10, 100, 1000, 10000, 100000
        tree_configurations = [
            "Rectangle_quad",
        ],
    ),
    # colored log prefixes; debug = true also shows the per-subsystem stages of VascularTrees
    debug = false,
    find_closest_tnodes = true,
    # === Matching options ===
    # greedy step + alternating step (Hungarian) for the closest terminal nodes
    m_options = MatchingOptions(
        k_greedy = 3,
        max_iter = 10,
        tol = 1e-8,
        algorithm = AuctionAssignment(),
        compute_bound = false,
    )
)
    setup_logging(debug = debug)

    for tree_configuration ∈ t_options.tree_configurations
        for n_node ∈ t_options.n_nodes
            # fill the tree structure with the info for this tree
            tree_info =
                TreeStructure(; tree_configuration = tree_configuration, n_node = n_node, tree_components = trees.vascular_trees[tree_configuration])
            @info "Working on $(tree_info.graph_id)"
            # load (.lg and .csv), process and save (as .arrow) each graph (vascular tree)
            process_julia_graph(tree_info)
            # load (.arrow) every graph that this tree includes, collect info that we
            # need for the correct ODEs for the terminal part that connects all the parts of this tree
            # together and save it in one file (as .arrow)
            process_terminal_nodes(tree_info, find_closest_tnodes, m_options)
        end
    end
end

# run only when started as a script, not when included in the REPL
# (VS Code "Execute File in REPL" also includes the file, so call main() yourself there)
if abspath(PROGRAM_FILE) == @__FILE__
    main()
end
